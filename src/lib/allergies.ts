// NEIS 알레르기 표준 코드 (식약처 고시 — 19종).
// 메뉴명 끝에 "(1.5.8)" 형태로 박혀오는 숫자를 사람 이름으로 변환.
const ALLERGY_NAMES: Record<string, string> = {
  '1': '난류',
  '2': '우유',
  '3': '메밀',
  '4': '땅콩',
  '5': '대두',
  '6': '밀',
  '7': '고등어',
  '8': '게',
  '9': '새우',
  '10': '돼지고기',
  '11': '복숭아',
  '12': '토마토',
  '13': '아황산류',
  '14': '호두',
  '15': '닭고기',
  '16': '쇠고기',
  '17': '오징어',
  '18': '조개류',
  '19': '잣',
};

/** 알레르기 번호 배열 → "난류, 우유, 대두" 같은 사람 이름. */
export function formatAllergyNames(codes: string[]): string {
  return codes
    .map((c) => ALLERGY_NAMES[c] ?? c) // 미정의 코드는 숫자 그대로
    .join(', ');
}
